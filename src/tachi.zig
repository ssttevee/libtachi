pub const Options = struct {
    /// PEM trust bundle for repository HTTPS; null uses the OS roots.
    ca_file: ?[]const u8 = null,
    /// Directory where the host persists preferences, cookies and converted APKs.
    data_dir: []const u8,
    cache_dir: ?[]const u8 = null,
    /// Path to tachi-host.jar. Defaults to $TACHI_HOST_JAR, then the copy
    /// embedded at build time (`-Dembed-host-jar`, extracted into `cache_dir`),
    /// then tachi-host.jar beside the executable or in ../lib (where
    /// `zig build` installs it), then ./tachi-host.jar and
    /// ./host/build/libs/tachi-host.jar.
    host_jar: ?[]const u8 = null,
    /// Extra jars for the JVM classpath (e.g. a JavaScript engine implementation).
    extra_classpath: []const []const u8 = &.{},
    user_agent: ?[]const u8 = null,
    app_version_name: ?[]const u8 = null,
    app_version_code: ?i32 = null,
    package_name: ?[]const u8 = null,
    verbose: bool = false,
    /// Receives android.util.Log output. Called from arbitrary JVM threads.
    log_fn: ?LogFn = null,
    log_user_data: ?*anyopaque = null,
    /// JVM selection; ignored when `existing_vm` is set.
    java_home: ?[]const u8 = null,
    libjvm_path: ?[]const u8 = null,
    jvm_options: []const []const u8 = &.{},
    /// Keep a class-data-sharing archive of the host in `cache_dir`, which
    /// roughly halves JVM start-up. JDK 19+ writes it on first exit; on JDK
    /// 17 and 18 call `Runtime.saveStartupCache`.
    class_data_sharing: bool = true,
    /// Route the host's OkHttp sockets through Zig, including TLS against
    /// `ca_file`. For JVMs without a JIT, where Java's TLS is very slow.
    native_transport: bool = false,
    /// Reuse a VM that already exists (Android: the JavaVM* from JNI_OnLoad).
    /// The host jar/dex must already be loadable by that VM's system class loader.
    existing_vm: ?*jni.JavaVM = null,
    /// Environment consulted for $TACHI_HOST_JAR, $TACHI_LIBJVM and $JAVA_HOME.
    /// Pass `init.minimal.environ` from `main`; the default looks nothing up.
    environ: Environ = .empty,
};

