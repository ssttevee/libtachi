    /// Downloads a page's image through the source's HTTP client.
    /// `page_json` is a `Page` object; `imageUrl` may be null, in which case
    /// the source's `getImageUrl` is consulted first.
    pub fn fetchImage(self: *Runtime, source_id: i64, page_json: []const u8) Error!Image {
        const Work = struct {
            fn run(rt: *Runtime, args: struct { i64, []const u8 }) Error!Image {
                return rt.fetchImageDirect(args[0], args[1]);
            }
        };
        return self.runCancelable(Image, Work.run, .{ source_id, page_json });
    }

    fn fetchImageDirect(self: *Runtime, source_id: i64, page_json: []const u8) Error!Image {
        const env = try self.frame();
        defer _ = env.f.PopLocalFrame(env, null);

        const arr = try self.callStatic(env, .fetchImage, .{ source_id, page_json }) orelse {
            // fetchImage reports failure out-of-band so the byte[] stays raw image data.
            if (try self.callStatic(env, .lastError, .{})) |e| {
                const msg = try bytesFromArray(self.gpa, env, e);
                defer self.gpa.free(msg);
                if (setErrorFromJson(self.gpa, msg)) |err| return err;
                setLastError(msg);
            } else setLastError("fetchImage failed");
            return extensionFailure();
        };
        const bytes = try bytesFromArray(self.gpa, env, arr);
        errdefer self.gpa.free(bytes);
        const mime = if (try self.callStatic(env, .lastImageMime, .{})) |m| try bytesFromArray(self.gpa, env, m) else null;
        return .{ .bytes = bytes, .mime = mime };
    }

    // ---- JNI plumbing ------------------------------------------------------------

    /// Attaches the thread and opens a JNI local frame; pair with PopLocalFrame.
    fn frame(self: *Runtime) Error!*jni.JNIEnv {
        const env = try self.vm.env();
        if (env.f.PushLocalFrame(env, 32) != jni.JNI_OK) {
            if (env.f.ExceptionCheck(env) != 0) env.f.ExceptionClear(env);
            return error.OutOfMemory;
        }
        return env;
    }

    /// Marshals a Zig tuple into `jvalue`s: `i64` -> `J`, `[]const u8` -> `byte[]`.
    /// The arrays are local refs owned by the caller's frame.
    fn marshal(env: *jni.JNIEnv, comptime method: BridgeMethod, args: method.Args()) Error![args.len]jni.jvalue {
        var out: [args.len]jni.jvalue = undefined;
        inline for (args, 0..) |arg, i| {
            out[i] = switch (@TypeOf(arg)) {
                i64 => .{ .j = arg },
                []const u8 => .{ .l = try newByteArray(env, arg) },
                else => unreachable,
            };
        }
        return out;
    }

    /// Calls a static object-returning bridge method inside the caller's frame.
    fn callStatic(self: *Runtime, env: *jni.JNIEnv, comptime method: BridgeMethod, args: method.Args()) Error!jni.jobject {
        comptime std.debug.assert(method.returnsBytes());
        if (self.methods.get(method) == null) return error.BridgeMethodNotFound;
        const jargs = try marshal(env, method, args);
        const result = env.f.CallStaticObjectMethodA(env, self.bridge, self.methods.get(method), &jargs);
        if (env.f.ExceptionCheck(env) != 0) {
            describeException(env);
            return error.JavaException;
        }
        return result;
    }

    /// Opens a frame, calls a `byte[]`-returning method and copies the reply out.
    fn invokeInFrame(self: *Runtime, comptime method: BridgeMethod, args: method.Args()) Error![]u8 {
        const Work = struct {
            fn run(rt: *Runtime, parameters: method.Args()) Error![]u8 {
                return rt.invokeInFrameDirect(method, parameters);
            }
        };
        return self.runCancelable([]u8, Work.run, args);
    }

    fn invokeInFrameDirect(self: *Runtime, comptime method: BridgeMethod, args: method.Args()) Error![]u8 {
        const env = try self.frame();
        defer _ = env.f.PopLocalFrame(env, null);
        const arr = try self.callStatic(env, method, args) orelse return error.InvalidResponse;
        return bytesFromArray(self.gpa, env, arr);
    }

    /// Whether this host supports operation-scoped std.Io cancellation. Older
    /// host jars still load, but their JNI calls run synchronously.
    pub fn supportsCancellation(self: *const Runtime) bool {
        inline for (.{ BridgeMethod.beginOperation, .enterOperation, .cancelOperation, .endOperation }) |method| {
            if (self.methods.get(method) == null) return false;
        }
        return true;
    }

    fn operationControl(self: *Runtime, comptime method: BridgeMethod, args: method.Args()) Error!void {
        const bytes = try self.invokeInFrameDirect(method, args);
        defer self.gpa.free(bytes);
        const result = try parseEnvelope(bool, self.gpa, bytes);
        result.deinit();
    }

    fn runCancelable(self: *Runtime, comptime T: type, comptime work: anytype, args: anytype) Error!T {
        try self.io.checkCancel();
        if (!self.supportsCancellation()) return work(self, args);
        // A primitive return avoids allocating a JSON reply after registration:
        // even an allocator failure must leave us with the ID needed for cleanup.
        const env = try self.vm.env();
        const id = env.f.CallStaticLongMethodA(env, self.bridge, self.methods.get(.beginOperation), &.{});
        if (env.f.ExceptionCheck(env) != 0) {
            describeException(env);
            return error.JavaException;
        }
        const Context = struct {
            rt: *Runtime,
            id: i64,
            args: @TypeOf(args),
            message: [last_error_buf.len]u8 = undefined,
            message_len: usize = 0,

            fn execute(ctx: *@This()) Error!T {
                defer ctx.rt.detachThread();
                defer ctx.rt.operationControl(.endOperation, .{ctx.id}) catch {};
                setLastError("");
                return ctx.executeInner() catch |err| {
                    const detail = lastError();
                    ctx.message_len = @min(detail.len, ctx.message.len);
                    @memcpy(ctx.message[0..ctx.message_len], detail[0..ctx.message_len]);
                    return err;
                };
            }
            fn executeInner(ctx: *@This()) Error!T {
                try ctx.rt.operationControl(.enterOperation, .{ctx.id});
                return work(ctx.rt, ctx.args);
            }
            fn cancel(ctx: *@This()) void {
                ctx.rt.operationControl(.cancelOperation, .{ctx.id}) catch {};
            }
            fn discard(ctx: *@This(), value: T) void {
                if (T == Image) value.deinit(ctx.rt.gpa) else ctx.rt.gpa.free(value);
            }
        };
        var context: Context = .{ .rt = self, .id = id, .args = args };
        // Covers cancellation/concurrency failure before the worker enters.
        // endOperation is idempotent; the worker clears its thread-local context.
        defer self.operationControl(.endOperation, .{context.id}) catch {};
        return cancelable.run(T, self.io, &context, Context.execute, Context.cancel, Context.discard) catch |err| {
            if (err != error.Canceled and context.message_len > 0) setLastError(context.message[0..context.message_len]);
            return err;
        };
    }

    /// Reply's `ok` payload re-serialised as JSON, owned by the caller.
    fn invokeJson(self: *Runtime, comptime method: BridgeMethod, args: method.Args()) Error![]u8 {
        const reply = try self.invokeInFrame(method, args);
        defer self.gpa.free(reply);
        return unwrapOk(self.gpa, reply);
    }

    /// Reply's `ok` payload decoded as `T`.
    fn invokeParsed(self: *Runtime, comptime T: type, comptime method: BridgeMethod, args: method.Args()) Error!Result(T) {
        const reply = try self.invokeInFrame(method, args);
        defer self.gpa.free(reply);
        return parseEnvelope(T, self.gpa, reply);
    }
};

/// `dir` made to exist and resolved to an absolute path (owned by caller).
fn absoluteDir(gpa: std.mem.Allocator, io: Io, dir: []const u8) Error![:0]u8 {
    const cwd = Io.Dir.cwd();
    cwd.createDirPath(io, dir) catch |e| {
        setLastErrorFmt("{s}: {s}", .{ dir, @errorName(e) });
        return error.FileSystemError;
    };
    return cwd.realPathFileAlloc(io, dir, gpa) catch |e| switch (e) {
        error.OutOfMemory => error.OutOfMemory,
        else => {
            setLastErrorFmt("{s}: {s}", .{ dir, @errorName(e) });
            return error.FileSystemError;
        },
    };
}

fn dupeStrings(gpa: std.mem.Allocator, list: []const []const u8) Error![]const []const u8 {
    const out = try gpa.alloc([]const u8, list.len);
    var n: usize = 0;
    errdefer {
        for (out[0..n]) |s| gpa.free(s);
        gpa.free(out);
    }
    for (list) |s| {
        out[n] = try gpa.dupe(u8, s);
        n += 1;
    }
    return out;
}

/// Decodes a bare (non-envelope) JSON document into a `Result`.
fn parseValue(comptime T: type, gpa: std.mem.Allocator, json: []const u8) Error!Result(T) {
    // Wrap so `Result` keeps its single representation.
    const wrapped = std.mem.concat(gpa, u8, &.{ "{\"ok\":", json, "}" }) catch return error.OutOfMemory;
    defer gpa.free(wrapped);
    return parseEnvelope(T, gpa, wrapped);
}

fn findGlobalClass(env: *jni.JNIEnv, name: [*:0]const u8) Error!jni.jclass {
    const class = env.f.FindClass(env, name) orelse {
        describeException(env);
        return error.BridgeClassNotFound;
    };
    defer env.f.DeleteLocalRef(env, class);
    return env.f.NewGlobalRef(env, class) orelse error.OutOfMemory;
}

fn newByteArray(env: *jni.JNIEnv, bytes: []const u8) Error!jni.jbyteArray {
    const arr = env.f.NewByteArray(env, @intCast(bytes.len)) orelse return error.OutOfMemory;
    if (bytes.len > 0) env.f.SetByteArrayRegion(env, arr, 0, @intCast(bytes.len), @ptrCast(bytes.ptr));
    return arr;
}

fn bytesFromArray(gpa: std.mem.Allocator, env: *jni.JNIEnv, arr: jni.jbyteArray) Error![]u8 {
    const len: usize = @intCast(env.f.GetArrayLength(env, arr));
    const out = try gpa.alloc(u8, len);
    if (len > 0) env.f.GetByteArrayRegion(env, arr, 0, @intCast(len), @ptrCast(out.ptr));
    return out;
}

/// Records a pending JVM exception into `lastError` and clears it.
fn describeException(env: *jni.JNIEnv) void {
    const exc = env.f.ExceptionOccurred(env) orelse return;
    env.f.ExceptionClear(env);
    defer env.f.DeleteLocalRef(env, exc);
    const obj_cls = env.f.FindClass(env, "java/lang/Object") orelse return;
    defer env.f.DeleteLocalRef(env, obj_cls);
    const to_string = env.f.GetMethodID(env, obj_cls, "toString", "()Ljava/lang/String;") orelse return;
    const str = env.f.CallObjectMethodA(env, exc, to_string, &[_]jni.jvalue{}) orelse return;
    defer env.f.DeleteLocalRef(env, str);
    if (env.f.ExceptionCheck(env) != 0) {
        env.f.ExceptionClear(env);
        setLastError("<exception while describing exception>");
        return;
    }
    const chars = env.f.GetStringUTFChars(env, str, null);
    defer env.f.ReleaseStringUTFChars(env, str, chars);
    setLastError(std.mem.sliceTo(chars, 0));
}

// ---- envelope handling ---------------------------------------------------------

/// Returns the `ok` payload re-serialised as JSON, or records the error.
fn unwrapOk(gpa: std.mem.Allocator, reply: []const u8) Error![]u8 {
    const r = try parseEnvelope(std.json.Value, gpa, reply);
    defer r.deinit();
    return std.json.Stringify.valueAlloc(gpa, r.value(), .{}) catch return error.OutOfMemory;
}

fn checkEnvelope(gpa: std.mem.Allocator, reply: []const u8) Error!void {
    const r = try parseEnvelope(std.json.Value, gpa, reply);
    r.deinit();
}

fn parseEnvelope(comptime T: type, gpa: std.mem.Allocator, reply: []const u8) Error!Result(T) {
    const parsed = std.json.parseFromSlice(models.Envelope(T), gpa, reply, models.parse_options) catch |e| {
        setLastError(@errorName(e));
        return error.InvalidResponse;
    };
    errdefer parsed.deinit();
    if (parsed.value.@"error") |e| {
        return setErrorInfo(e);
    }
    if (parsed.value.ok == null) return error.InvalidResponse;
    return .{ .parsed = parsed };
}

/// Classifies only the host's explicit unsupported Cloudflare solver failure.
/// HTTP 403, source exceptions and unsuccessful registered solvers stay retryable.
fn extensionFailure() Error {
    const detail = lastError();
    const exception = "eu.kanade.tachiyomi.network.interceptor.CloudflareBypassException: ";
    if (std.mem.startsWith(u8, detail, exception) and
        std.mem.startsWith(u8, detail[exception.len..], "Cloudflare challenge on ") and
        std.mem.endsWith(u8, detail, "; no CloudflareSolver is registered with the tachi host."))
        return error.BrowserVerificationRequired;
    return error.ExtensionError;
}

fn setErrorInfo(e: models.ErrorInfo) Error {
    setLastErrorFmt("{s}: {s}", .{ e.type, e.message orelse "" });
    if (e.code) |code| if (std.mem.eql(u8, code, "browser_verification_required")) return error.BrowserVerificationRequired;
    return extensionFailure();
}

/// Decodes an ErrorDto JSON blob into lastError and preserves its typed failure.
fn setErrorFromJson(gpa: std.mem.Allocator, json: []const u8) ?Error {
    const parsed = std.json.parseFromSlice(models.ErrorInfo, gpa, json, models.parse_options) catch return null;
    defer parsed.deinit();
    return setErrorInfo(parsed.value);
}

// ---- host jar discovery --------------------------------------------------------

const host_jar_candidates = [_][]const u8{
    "tachi-host.jar",
    "host/build/libs/tachi-host.jar",
    "../host/build/libs/tachi-host.jar",
};

fn findHostJar(gpa: std.mem.Allocator, io: Io, environ: Environ, explicit: ?[]const u8, cache_dir: []const u8) Error![]u8 {
    if (explicit) |p| {
        if (!jvm.fileExists(io, p)) return error.HostJarNotFound;
        return gpa.dupe(u8, p);
    }
    if (jvm.getenv(environ, "TACHI_HOST_JAR")) |p| {
        if (jvm.fileExists(io, p)) return gpa.dupe(u8, p);
    }
    if (host_jar.bytes) |bytes| return extractHostJar(gpa, io, bytes, cache_dir);
    if (try besideExecutable(gpa, io)) |p| return p;
    for (host_jar_candidates) |p| {
        if (jvm.fileExists(io, p)) return gpa.dupe(u8, p);
    }
    return error.HostJarNotFound;
}

/// `<prefix>/bin/tachi-cli` finds `<prefix>/lib/tachi-host.jar`, the layout
/// `zig build` installs; a jar dropped next to the executable also works.
fn besideExecutable(gpa: std.mem.Allocator, io: Io) Error!?[]u8 {
    const exe_dir = std.process.executableDirPathAlloc(io, gpa) catch return null;
    defer gpa.free(exe_dir);
    for ([_][]const u8{ ".", "../lib" }) |rel| {
        const p = try std.fs.path.join(gpa, &.{ exe_dir, rel, "tachi-host.jar" });
        if (jvm.fileExists(io, p)) return p;
        gpa.free(p);
    }
    return null;
}

/// Writes the embedded jar to `<cache_dir>/tachi-host-<hash>.jar` once; later
/// runs find it already there. HotSpot maps the file, so this is the cheapest
/// way to hand it the classes: no copy per run, and CDS can key off the path.
fn extractHostJar(gpa: std.mem.Allocator, io: Io, bytes: []const u8, cache_dir: []const u8) Error![]u8 {
    const path = try std.fmt.allocPrint(gpa, "{s}/tachi-host-{s}.jar", .{ cache_dir, host_jar.hash });
    errdefer gpa.free(path);
    const cwd = Io.Dir.cwd();
    if (cwd.statFile(io, path, .{})) |st| {
        if (st.size == bytes.len) return path;
    } else |_| {}
    // Write-then-rename so a concurrent first run never sees a partial jar.
    const part = try std.fmt.allocPrint(gpa, "{s}.part", .{path});
    defer gpa.free(part);
    cwd.writeFile(io, .{ .sub_path = part, .data = bytes }) catch |e| {
        setLastErrorFmt("{s}: {s}", .{ part, @errorName(e) });
        return error.FileSystemError;
    };
    cwd.rename(part, cwd, path, io) catch |e| {
        setLastErrorFmt("{s}: {s}", .{ path, @errorName(e) });
        return error.FileSystemError;
    };
    return path;
}

// ---- log hook (JVM -> native) -------------------------------------------------

fn nativeLog(env: *jni.JNIEnv, cls: jni.jclass, level: jni.jint, tag: jni.jbyteArray, msg: jni.jbyteArray) callconv(.c) void {
    _ = cls;
    const f = g_log_fn orelse return;
    var tag_buf: [256:0]u8 = undefined;
    var msg_buf: [16384:0]u8 = undefined;
    f(@fromBackingInt(@intCast(level)), copyArray(env, tag, &tag_buf), copyArray(env, msg, &msg_buf), g_log_ud);
}

fn copyArray(env: *jni.JNIEnv, arr: jni.jbyteArray, buf: [:0]u8) [*:0]const u8 {
    if (arr == null) {
        buf[0] = 0;
        return buf.ptr;
    }
    const len: usize = @min(@as(usize, @intCast(env.f.GetArrayLength(env, arr))), buf.len);
    if (len > 0) env.f.GetByteArrayRegion(env, arr, 0, @intCast(len), @ptrCast(buf.ptr));
    buf[len] = 0;
    return buf.ptr;
}

fn registerLogHook(env: *jni.JNIEnv) Error!void {
    const cls = env.f.FindClass(env, "dev/tachi/host/NativeHooks") orelse {
        describeException(env);
        return error.BridgeClassNotFound;
    };
    defer env.f.DeleteLocalRef(env, cls);
    const methods = [_]jni.JNINativeMethod{.{
        .name = "log",
        .signature = "(I[B[B)V",
        .fnPtr = @ptrCast(@constCast(&nativeLog)),
    }};
    if (env.f.RegisterNatives(env, cls, &methods, methods.len) != jni.JNI_OK) {
        describeException(env);
        return error.BridgeMethodNotFound;
    }
}

