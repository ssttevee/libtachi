/// A decoded bridge response; `value()` borrows from the arena freed by `deinit`.
pub fn Result(comptime T: type) type {
    return struct {
        parsed: std.json.Parsed(models.Envelope(T)),

        pub fn value(self: @This()) T {
            return self.parsed.value.ok.?;
        }

        pub fn deinit(self: @This()) void {
            self.parsed.deinit();
        }
    };
}

// ---- last error (per thread) ---------------------------------------------------

/// Kept NUL-terminated so the C API can hand the buffer out without copying.
threadlocal var last_error_buf: [8192:0]u8 = @splat(0);
threadlocal var last_error_len: usize = 0;

/// Message for the most recent `JavaException` / `ExtensionError` on this thread.
pub fn lastError() [:0]const u8 {
    return last_error_buf[0..last_error_len :0];
}

pub fn setLastError(msg: []const u8) void {
    const n = @min(msg.len, last_error_buf.len);
    @memcpy(last_error_buf[0..n], msg[0..n]);
    last_error_buf[n] = 0;
    last_error_len = n;
}

pub fn setLastErrorFmt(comptime fmt: []const u8, args: anytype) void {
    var w: Io.Writer = .fixed(&last_error_buf);
    w.print(fmt, args) catch {}; // truncation is fine for a diagnostic
    last_error_len = w.end;
    last_error_buf[last_error_len] = 0;
}

var g_log_fn: ?LogFn = null;
var g_log_ud: ?*anyopaque = null;

/// Routes a native-side message through the embedder's `log_fn`, tagged "tachi".
pub fn log(level: LogLevel, comptime fmt: []const u8, args: anytype) void {
    const f = g_log_fn orelse return;
    var buf: [1024:0]u8 = undefined;
    var w: Io.Writer = .fixed(&buf);
    w.print(fmt, args) catch {};
    buf[w.end] = 0;
    f(level, "tachi", buf[0..w.end :0], g_log_ud);
}

// ---- bridge method table -------------------------------------------------------

/// Static methods of `dev.tachi.host.Bridge`, with their JNI signatures.
/// The enum tag is the Java method name, so adding a bridge method is one line.
pub const BridgeMethod = enum {
    init,
    install,
    register,
    uninstall,
    listExtensions,
    extensionToLoad,
    loadSource,
    call,
    fetchImage,
    lastImageMime,
    lastError,
    shutdown,
    reloadPreferences,
    beginOperation,
    enterOperation,
    cancelOperation,
    endOperation,

    /// Methods older host jars lack; the runtime starts without them.
    fn optional(m: BridgeMethod) bool {
        return switch (m) {
            .reloadPreferences, .beginOperation, .enterOperation, .cancelOperation, .endOperation => true,
            else => false,
        };
    }

    pub fn signature(m: BridgeMethod) [:0]const u8 {
        return switch (m) {
            .init, .install, .register, .uninstall => "([B)[B",
            .listExtensions, .lastImageMime, .lastError, .reloadPreferences => "()[B",
            .beginOperation => "()J",
            .extensionToLoad, .loadSource, .enterOperation, .cancelOperation, .endOperation => "(J)[B",
            .call => "(J[B[B)[B",
            .fetchImage => "(J[B)[B",
            .shutdown => "()V",
        };
    }

    /// Zig argument tuple derived from the JNI signature at compile time.
    fn Args(comptime m: BridgeMethod) type {
        return comptime blk: {
            const sig = m.signature();
            var types: []const type = &.{};
            var i: usize = 1;
            while (sig[i] != ')') : (i += 1) {
                const T = switch (sig[i]) {
                    'J' => i64,
                    '[' => array: {
                        i += 1;
                        if (sig[i] != 'B') @compileError("unsupported bridge array type");
                        break :array []const u8;
                    },
                    else => @compileError("unsupported bridge argument type"),
                };
                types = types ++ &[_]type{T};
            }
            break :blk @Tuple(types);
        };
    }

    /// `true` when the method returns `byte[]`, so `invokeBytes` may be used.
    pub fn returnsBytes(m: BridgeMethod) bool {
        return std.mem.endsWith(u8, m.signature(), ")[B");
    }
};

const MethodIds = std.EnumArray(BridgeMethod, jni.jmethodID);

pub const Runtime = struct {
    gpa: std.mem.Allocator,
    io: Io,
    vm: jvm.Vm,
    bridge: jni.jclass,
    methods: MethodIds,
    /// Absolute `Options.data_dir`; the registry and downloads live under it.
    data_dir: [:0]u8,
    /// Absolute `Options.cache_dir`; the extracted host jar and CDS archive live here.
    cache_dir: [:0]u8,
    /// Serialises registry read-modify-write cycles across threads.
    lock: Io.Mutex = .init,
    /// extensions-lib versions the host jar reported at `init`.
    supported_lib_versions: []const []const u8,
    ca_file: ?[]u8 = null,

    // Management (registry, repositories): see manage.zig.
    pub const installExtension = manage.installExtension;
    pub const uninstallExtension = manage.uninstallExtension;
    pub const restore = manage.restore;
    pub const repoList = manage.repoList;
    pub const repoListJson = manage.repoListJson;
