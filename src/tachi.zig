    pub const repoUpdate = manage.repoUpdate;
    pub const RepoOptions = manage.RepoOptions;
    pub const RepoEntry = manage.RepoEntry;

    pub fn init(gpa: std.mem.Allocator, io: Io, opts: Options) Error!*Runtime {
        const self = try gpa.create(Runtime);
        errdefer gpa.destroy(self);
        self.* = .{
            .gpa = gpa,
            .io = io,
            .vm = undefined,
            .bridge = undefined,
            .methods = undefined,
            .data_dir = try absoluteDir(gpa, io, opts.data_dir),
            .cache_dir = undefined,
            .supported_lib_versions = &.{},
        };
        errdefer gpa.free(self.data_dir);
        const default_cache = try std.fs.path.join(gpa, &.{ self.data_dir, "cache" });
        defer gpa.free(default_cache);
        self.cache_dir = try absoluteDir(gpa, io, opts.cache_dir orelse default_cache);
        errdefer gpa.free(self.cache_dir);
        if (opts.ca_file) |path| self.ca_file = try gpa.dupe(u8, path);
        errdefer if (self.ca_file) |path| gpa.free(path);

        self.vm = if (opts.existing_vm) |vm| jvm.Vm.adopt(vm) else try self.createVm(opts);
        errdefer self.vm.destroy();

        const env = try self.vm.env();
        self.bridge = try findGlobalClass(env, "dev/tachi/host/Bridge");
        errdefer env.f.DeleteGlobalRef(env, self.bridge);

        var ids: MethodIds = undefined;
        inline for (comptime std.enums.values(BridgeMethod)) |m| {
            ids.set(m, env.f.GetStaticMethodID(env, self.bridge, @tagName(m), m.signature()) orelse blk: {
                if (m.optional()) {
                    env.f.ExceptionClear(env);
                    break :blk null;
                }
                describeException(env);
                return error.BridgeMethodNotFound;
            });
        }
        self.methods = ids;

        if (opts.log_fn) |f| {
            g_log_fn = f;
            g_log_ud = opts.log_user_data;
            try registerLogHook(env);
        }

        if (!self.supportsCancellation()) log(.warn, "host jar lacks operation cancellation; JVM calls remain synchronous", .{});

        const native_transport = opts.native_transport and transport.register(env, gpa, io, self.ca_file);
        if (opts.native_transport and !native_transport) log(.warn, "native transport unavailable; using Java TLS", .{});

        // Build the RuntimeConfig JSON the Kotlin side expects.
        const config_json = std.json.Stringify.valueAlloc(gpa, .{
            .dataDir = opts.data_dir,
            .cacheDir = self.cache_dir,
            .userAgent = opts.user_agent,
            .appVersionName = opts.app_version_name,
            .appVersionCode = opts.app_version_code,
            .packageName = opts.package_name,
            .verbose = opts.verbose,
            .nativeLog = opts.log_fn != null,
            .nativeTransport = native_transport,
        }, .{ .emit_null_optional_fields = false }) catch return error.OutOfMemory;
        defer gpa.free(config_json);

        const reply = try self.invokeInFrame(.init, .{config_json});
        defer gpa.free(reply);
        const info = try parseEnvelope(models.InitInfo, gpa, reply);
        defer info.deinit();
        self.supported_lib_versions = try dupeStrings(gpa, info.value().supportedLibVersions);
        return self;
    }

    fn createVm(self: *Runtime, opts: Options) Error!jvm.Vm {
        const gpa = self.gpa;
        const jar = try findHostJar(gpa, self.io, opts.environ, opts.host_jar, self.cache_dir);
        defer gpa.free(jar);
        const cp = try std.mem.concat(gpa, []const u8, &.{ &.{jar}, opts.extra_classpath });
        defer gpa.free(cp);
        // One archive per distinct jar: a rebuilt or relocated jar gets a fresh one
        // instead of a silently rejected stale one.
        const archive = if (opts.class_data_sharing)
            try std.fmt.allocPrint(gpa, "{s}/tachi-host-{x:0>16}.jsa", .{ self.cache_dir, std.hash.Wyhash.hash(0, jar) })
        else
            null;
        defer if (archive) |a| gpa.free(a);
        return jvm.Vm.create(gpa, self.io, .{
            .java_home = opts.java_home,
            .libjvm_path = opts.libjvm_path,
            .classpath = cp,
            .extra_options = opts.jvm_options,
            .cds_archive = archive,
            .environ = opts.environ,
        });
    }

    pub fn deinit(self: *Runtime) void {
        if (self.vm.env()) |env| {
            env.f.CallStaticVoidMethodA(env, self.bridge, self.methods.get(.shutdown), &[_]jni.jvalue{});
            if (env.f.ExceptionCheck(env) != 0) env.f.ExceptionClear(env);
            env.f.DeleteGlobalRef(env, self.bridge);
        } else |_| {}
        g_log_fn = null;
        self.vm.destroy();
        transport.unregister();
        for (self.supported_lib_versions) |v| self.gpa.free(v);
        self.gpa.free(self.supported_lib_versions);
        self.gpa.free(self.data_dir);
        self.gpa.free(self.cache_dir);
        if (self.ca_file) |path| self.gpa.free(path);
        self.gpa.destroy(self);
    }

    /// Detach the calling thread from the JVM. Call before a thread that used
    /// the runtime exits (not needed for the thread that called `init`).
    pub fn detachThread(self: *Runtime) void {
        self.vm.detach();
    }

    /// Saves a cache in `cache_dir` that makes later runtimes start faster.
    /// Call it once after the runtime has done some typical work, ideally
    /// while the app is idle: everything pauses briefly while it is written.
    /// Nothing happens if there is nothing to save.
    ///
    /// The cache is the JVM's class-data-sharing archive of the classes
    /// loaded so far. JDK 19+ writes it by itself on exit; JDK 17 and 18 only
    /// from a running VM, which is what this does.
    pub fn saveStartupCache(self: *Runtime) !void {
        return self.vm.saveClassArchive();
    }

    /// Whether `saveStartupCache` has a cache to save.
    pub fn startupCachePending(self: *const Runtime) bool {
        return self.vm.classArchivePending();
    }

